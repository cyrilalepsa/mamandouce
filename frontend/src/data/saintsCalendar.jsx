// Fonction pour obtenir le saint du jour
export function getSaintOfTheDay(date = new Date()) {
  const month = date.getMonth() + 1;
  const day = date.getDate();
  
  return saintsCalendar[month]?.[day] || null;
}

// Fonction pour vérifier si un prénom est fêté aujourd'hui
export function isNameCelebratedToday(userName, date = new Date()) {
  if (!userName) return false;
  
  const saint = getSaintOfTheDay(date);
  if (!saint) return false;
  
  const normalizedUserName = userName.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  const normalizedSaintName = saint.name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  
  // Vérifier le nom principal
  if (normalizedUserName === normalizedSaintName) return true;
  
  // Vérifier les variantes
  const normalizedVariants = saint.variants.map(v => 
    v.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "")
  );
  
  return normalizedVariants.includes(normalizedUserName);
}
